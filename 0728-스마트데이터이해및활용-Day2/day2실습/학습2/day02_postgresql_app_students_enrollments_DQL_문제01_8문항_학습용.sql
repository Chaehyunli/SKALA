SELECT
    s.student_no AS 학번,
    s.name AS 학생명,
    s.grade AS 학년,
    m.code AS 학과코드,
    m.name AS 학과명
FROM students s
LEFT JOIN majors m
       ON m.id = s.major_id
ORDER BY s.student_no;

-- 핵심 해설
-- students를 기준으로 LEFT JOIN하므로 학과가 없는 학생도 출력됩니다.
-- INNER JOIN을 사용하면 학과 미배정 학생이 결과에서 제외됩니다.


-- ============================================================================
-- [문제 2 정답] COALESCE를 이용한 미배정 학과 처리
-- ============================================================================

SELECT
    s.student_no AS 학번,
    s.name AS 학생명,
    COALESCE(m.name, '학과 미배정') AS 학과명
FROM students s
LEFT JOIN majors m
       ON m.id = s.major_id
ORDER BY s.student_no;

-- 핵심 해설
-- COALESCE는 왼쪽부터 확인하여 처음 만나는 NULL이 아닌 값을 반환합니다.
-- m.name이 NULL이면 두 번째 값인 '학과 미배정'이 반환됩니다.


-- ============================================================================
-- [문제 3 정답] CASE를 이용한 학점 등급 계산
-- ============================================================================

SELECT
    s.name AS 학생명,
    c.name AS 과목명,
    e.score AS 점수,
    CASE
        WHEN e.score IS NULL THEN '미입력'
        WHEN e.score >= 90 THEN 'A'
        WHEN e.score >= 80 THEN 'B'
        WHEN e.score >= 70 THEN 'C'
        WHEN e.score >= 60 THEN 'D'
        ELSE 'F'
    END AS 등급
FROM enrollments e
JOIN students s
     ON s.id = e.student_id
JOIN courses c
     ON c.id = e.course_id
ORDER BY s.name, c.name;

-- 핵심 해설
-- CASE는 위에서부터 조건을 검사하고 처음으로 참인 결과를 반환합니다.
-- 따라서 90점 조건보다 60점 조건을 먼저 쓰면 95점도 D로 판정됩니다.


-- ============================================================================
-- [문제 4 정답] 수강 연도·월과 학기 구분
-- ============================================================================

SELECT
    s.name AS 학생명,
    c.name AS 과목명,
    e.enrolled_at AS 수강신청일,
    EXTRACT(YEAR FROM e.enrolled_at)::integer AS 수강연도,
    EXTRACT(MONTH FROM e.enrolled_at)::integer AS 수강월,
    CASE
        WHEN EXTRACT(MONTH FROM e.enrolled_at) BETWEEN 1 AND 6
            THEN '1학기'
        ELSE '2학기'
    END AS 학기구분
FROM enrollments e
JOIN students s
     ON s.id = e.student_id
JOIN courses c
     ON c.id = e.course_id
ORDER BY s.name, e.enrolled_at, c.name;

-- 핵심 해설
-- EXTRACT는 날짜에서 연도나 월을 숫자로 추출합니다.
-- 샘플 데이터의 2025-03-02는 1학기, 2025-09-01은 2학기입니다.


-- ============================================================================
-- [문제 5 정답] 수강신청 후 경과 일수 계산
-- ============================================================================

SELECT
    s.name AS 학생명,
    c.name AS 과목명,
    e.enrolled_at AS 수강신청일,
    CURRENT_DATE AS 오늘날짜,
    CURRENT_DATE - e.enrolled_at AS 경과일수
FROM enrollments e
JOIN students s
     ON s.id = e.student_id
JOIN courses c
     ON c.id = e.course_id
ORDER BY 경과일수 DESC, s.name, c.name;

-- 핵심 해설
-- PostgreSQL에서 date - date의 결과는 두 날짜 사이의 일수인 정수입니다.
-- CURRENT_DATE는 쿼리를 실행하는 날짜에 따라 결과가 달라집니다.


-- ============================================================================
-- [문제 6 정답] 학생별 수강 과목 수와 평균점수
-- ============================================================================

SELECT
    s.student_no AS 학번,
    s.name AS 학생명,
    COUNT(e.course_id) AS 수강과목수,
    ROUND(AVG(e.score), 2) AS 평균점수
FROM students s
LEFT JOIN enrollments e
       ON e.student_id = s.id
GROUP BY
    s.id,
    s.student_no,
    s.name
ORDER BY 평균점수 DESC NULLS LAST, s.student_no;

-- 핵심 해설
-- LEFT JOIN 결과에서 COUNT(*)를 사용하면 수강정보가 없는 학생도 1로
-- 계산될 수 있으므로, 실제 수강 행에서만 값이 있는 e.course_id를 계산합니다.


-- ============================================================================
-- [문제 7 정답] 학생별 평균점수에 따른 성취도 판정
-- ============================================================================

SELECT
    s.student_no AS 학번,
    s.name AS 학생명,
    COALESCE(m.name, '학과 미배정') AS 학과명,
    COUNT(e.course_id) AS 수강과목수,
    ROUND(AVG(e.score), 2) AS 평균점수,
    CASE
        WHEN AVG(e.score) IS NULL THEN '평가 불가'
        WHEN AVG(e.score) >= 90 THEN '최우수'
        WHEN AVG(e.score) >= 85 THEN '우수'
        WHEN AVG(e.score) >= 80 THEN '보통'
        ELSE '노력 필요'
    END AS 성취도
FROM students s
LEFT JOIN majors m
       ON m.id = s.major_id
LEFT JOIN enrollments e
       ON e.student_id = s.id
GROUP BY
    s.id,
    s.student_no,
    s.name,
    m.name
ORDER BY 평균점수 DESC NULLS LAST, s.student_no;

-- 핵심 해설
-- 먼저 학생별로 GROUP BY한 후 AVG(e.score)를 성취도 기준과 비교합니다.
-- 수강정보가 없다면 AVG 결과가 NULL이므로 '평가 불가'가 됩니다.


-- ============================================================================
-- [문제 8 정답] 전체 평균보다 평균점수가 높은 학생 조회
-- ============================================================================

WITH student_average AS (
    SELECT
        s.id AS student_id,
        s.student_no,
        s.name AS student_name,
        s.major_id,
        AVG(e.score) AS avg_score
    FROM students s
    JOIN enrollments e
         ON e.student_id = s.id
    GROUP BY
        s.id,
        s.student_no,
        s.name,
        s.major_id
),
overall_average AS (
    SELECT AVG(score) AS avg_score
    FROM enrollments
)
SELECT
    sa.student_no AS 학번,
    sa.student_name AS 학생명,
    COALESCE(m.name, '학과 미배정') AS 학과명,
    ROUND(sa.avg_score, 2) AS 학생평균점수,
    ROUND(oa.avg_score, 2) AS 전체평균점수,
    ROUND(sa.avg_score - oa.avg_score, 2) AS 평균과의차이
FROM student_average sa
LEFT JOIN majors m
       ON m.id = sa.major_id
CROSS JOIN overall_average oa
WHERE sa.avg_score > oa.avg_score
ORDER BY 학생평균점수 DESC, sa.student_no;

-- 핵심 해설
-- student_average는 학생별 평균을, overall_average는 전체 성적 평균을
-- 계산합니다. 전체 평균 CTE는 한 행이므로 CROSS JOIN하여 모든 학생 평균과
-- 비교할 수 있습니다.


