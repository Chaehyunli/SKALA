-- 17. [고급] 트리거 함수 — 주문 변경 자동 감사
-- ============================================================================
--트리거 함수에는 일반 매개변수가 없어도 PostgreSQL이 다음과 같은 특별한 값을 자동으로 제공합니다.
--NEW
--OLD
--TG_OP
--TG_TABLE_NAME
--TG_TABLE_SCHEMA

CREATE OR REPLACE FUNCTION proc_lab.fn_audit_orders()
RETURNS trigger		--일반 함수와 트리거 함수 차이 : 트리거 함수는 일반 함수와 달리 직접 호출하기 위한 함수가 아닙니다.
LANGUAGE plpgsql
SECURITY definer	--함수를 호출한 사용자의 권한이 아니라 함수 소유자의 권한으로 실행한다는 의미입니다.
SET search_path = pg_catalog, proc_lab, pg_temp
AS $function$
--| 스키마          | 역할                       |
--| ------------ | ------------------------ |
--| `pg_catalog` | PostgreSQL 기본 함수와 시스템 객체 |
--| `proc_lab`   | 실습용 테이블과 함수              |
--| `pg_temp`    | 임시 스키마, 가장 뒤에 배치         |

BEGIN
	--실제 값이 변경된 경우에만 기록하고 싶다면 함수의 시작 부분에 다음 조건을 추가합니다.
	IF TG_OP = 'UPDATE'
       AND NEW IS NOT DISTINCT FROM OLD THEN
        RETURN NEW;
    END IF;

    INSERT INTO proc_lab.audit_log		--대상 테이블을 지정하는 것도 좋습니다.
        (table_name, operation, row_id, old_data, new_data)	--감사 로그 입력
			--| 컬럼           | 저장 내용                        |
			--| ------------ | ------------------------------ |
			--| `table_name` | 변경된 테이블명                     |
			--| `operation`  | `INSERT`, `UPDATE`, `DELETE`   |
			--| `row_id`     | 변경된 주문번호                     |
			--| `old_data`   | 변경 전 데이터                     |
			--| `new_data`   | 변경 후 데이터                     |
    VALUES
        (
			--TG_TABLE_SCHEMA	--스키마명도 필요하다면 이 변수를 사용할 수 있습니다.
            TG_TABLE_NAME,		--트리거가 실행된 테이블 이름입니다.현재 트리거는 orders에 연결되어 있습니다.
            TG_OP,				--트리거를 발생시킨 SQL 작업 종류를 나타냅니다.오퍼레이션
            coalesce(			--변경된 주문번호 추출:먼저 NEW에서 order_id를 찾고, 값이 없으면 OLD에서 찾습니다.
                (to_jsonb(NEW) ->> 'order_id')::bigint,
                (to_jsonb(OLD) ->> 'order_id')::bigint
            ),
            CASE WHEN TG_OP IN ('UPDATE', 'DELETE')	--old_data 저장 조건
                 THEN to_jsonb(OLD) END,			--행 전체를 JSONB 객체로 변환합니다.
            CASE WHEN TG_OP IN ('INSERT', 'UPDATE')	--new_data 저장 조건
                 THEN to_jsonb(NEW) END				--행 전체를 JSONB 객체로 변환합니다.
        );
--NEW와 OLD는 변경 전후의 전체 행을 나타냅니다.
--	| 작업       | `OLD`  | `NEW`    |
--	| -------- | ------ | -------- |
--	| `INSERT` | 없음     | 새로 입력된 행 |
--	| `UPDATE` | 변경 전 행 | 변경 후 행   |
--	| `DELETE` | 삭제 전 행 | 없음       |

	
    IF TG_OP = 'DELETE' THEN		--DELETE일 때 RETURN OLD : DELETE: 삭제 전 행인 OLD
        RETURN OLD;
    END IF;

    RETURN NEW;						--INSERT, UPDATE: 변경 후 행인 NEW
--BEFORE 트리거 → RETURN 값이 중요
--AFTER 트리거  → RETURN 값이 무시됨
--따라서 현재 코드에서 RETURN OLD, RETURN NEW는 관례적으로 작성한 형태입니다.
END;
$function$;


--이 코드는 orders 테이블에 INSERT, UPDATE, DELETE가 발생할 때마다 변경 전후 데이터를 
--audit_log 테이블에 자동 저장하는 감사(Audit) 트리거입니다.
--사용자가 별도로 로그를 입력하지 않아도 주문 데이터가 변경되면 트리거가 자동으로 변경 이력을 기록합니다.

