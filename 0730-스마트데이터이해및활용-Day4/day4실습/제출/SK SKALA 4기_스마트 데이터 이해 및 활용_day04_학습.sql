CREATE OR REPLACE VIEW proc_lab.v_routine_inventory AS
SELECT n.nspname AS routine_schema,
       p.proname AS routine_name,
       CASE p.prokind
           WHEN 'f' THEN 'FUNCTION'
           WHEN 'p' THEN 'PROCEDURE'
           WHEN 'a' THEN 'AGGREGATE'
           WHEN 'w' THEN 'WINDOW'
       END AS routine_kind,
       pg_get_function_identity_arguments(p.oid) AS identity_arguments,
       l.lanname AS language_name,
       CASE p.provolatile
           WHEN 'i' THEN 'IMMUTABLE'
           WHEN 's' THEN 'STABLE'
           WHEN 'v' THEN 'VOLATILE'
       END AS volatility,
       CASE p.proparallel
           WHEN 's' THEN 'SAFE'
           WHEN 'r' THEN 'RESTRICTED'
           WHEN 'u' THEN 'UNSAFE'
       END AS parallel_safety,
       p.prosecdef AS security_definer,
       pg_get_userbyid(p.proowner) AS owner_name
FROM pg_catalog.pg_proc AS p
JOIN pg_catalog.pg_namespace AS n
  ON n.oid = p.pronamespace
JOIN pg_catalog.pg_language AS l
  ON l.oid = p.prolang
WHERE n.nspname = 'proc_lab'
  AND p.prokind IN ('f', 'p');

SELECT *
FROM v_routine_inventory
ORDER BY routine_kind, routine_name, identity_arguments;

