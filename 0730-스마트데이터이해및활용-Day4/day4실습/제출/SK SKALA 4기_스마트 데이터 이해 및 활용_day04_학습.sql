--3. email_normalized 중복 발견
--4. INSERT 대신 UPDATE
--5. 고객명과 이메일 수정
--6. 기존 customer_id 반환

SELECT customer_id, customer_name, email, email_normalized
FROM customers
WHERE email_normalized = 'jimin@example.com';
