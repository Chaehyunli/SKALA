--target_orders CTE에서 2026년 7월 주문만 먼저 선택하고, 
--item_json CTE가 그 주문들의 상품을 order_id별로 JSON 배열로 묶으면 
--2026년 7월 주문 영수증을 한 번에 만들 수 있습니다.
WITH target_orders AS MATERIALIZED (
    ----------------------------------------------------------------
    -- 1. 2026년 7월 주문만 먼저 선택
    ----------------------------------------------------------------
    SELECT
        o.order_id,
        o.customer_id,
        o.order_status,
        o.ordered_at,
        o.total_amount
    FROM proc_lab.orders AS o
    WHERE o.ordered_at >= DATE '2026-07-01'
      AND o.ordered_at <  DATE '2026-08-01'
),
item_json AS (
    ----------------------------------------------------------------
    -- 2. 선택된 주문들의 상품을 주문번호별 JSON 배열로 생성
    ----------------------------------------------------------------
    SELECT
        oi.order_id,
        jsonb_agg(
            jsonb_build_object(
                'product_id',   p.product_id,
                'product_name', p.product_name,
                'quantity',     oi.quantity,
                'unit_price',   oi.unit_price,
                'line_amount',  oi.line_amount
            )
            ORDER BY oi.order_item_id
        ) AS items
    FROM target_orders AS t
    JOIN proc_lab.order_items AS oi
      ON oi.order_id = t.order_id
    JOIN proc_lab.products AS p
      ON p.product_id = oi.product_id
    GROUP BY oi.order_id
),
receipts AS (
    ----------------------------------------------------------------
    -- 3. 주문, 고객, 상품 JSON을 합쳐 영수증 생성
    ----------------------------------------------------------------
    SELECT
        t.order_id,
        t.ordered_at,
        jsonb_build_object(
            'order_id',     t.order_id,
            'status',       t.order_status,
            'ordered_at',   t.ordered_at,
            'customer', jsonb_build_object(
                'customer_id', c.customer_id,
                'name',        c.customer_name,
                'email',       c.email
            ),
            'total_amount', t.total_amount,
            'items', coalesce(
                i.items,
                '[]'::jsonb
            )
        ) AS receipt
    FROM target_orders AS t
    JOIN proc_lab.customers AS c
      ON c.customer_id = t.customer_id
    LEFT JOIN item_json AS i
      ON i.order_id = t.order_id
)
