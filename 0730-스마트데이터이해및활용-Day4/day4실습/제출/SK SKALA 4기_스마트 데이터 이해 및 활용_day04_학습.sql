-- 16. [고급 함수] 안전한 동적 SQL — regclass + format + USING
-- ============================================================================
--이 함수는 동적 SQL의 식별자와 값은 처리 방법이 다르다는 점을 보여주는 예제입니다.
CREATE OR REPLACE FUNCTION proc_lab.fn_count_rows_dynamic(
    p_table  regclass,	--조회 대상 테이블 : 테이블 이름을 단순 text로 받는 것보다 안전합니다.
    p_column name,		--조건을 적용할 컬럼
    p_value  text		--비교할 값
)
RETURNS bigint			--PostgreSQL의 count(*) 반환 타입이 bigint이기 때문입니다.
LANGUAGE plpgsql
stable					--이 함수는 테이블을 조회하지만 데이터를 변경하지 않습니다.그러므로 IMMUTABLE은 적절하지 않습니다
AS $function$
DECLARE
    v_sql   text;
    v_count bigint;
BEGIN
    /*
      식별자(테이블/컬럼)는 바인딩할 수 없으므로 regclass와 %I를 사용한다.
      값은 문자열에 붙이지 말고 반드시 USING으로 전달한다.

      교육용 범용 예제라 컬럼을 text로 변환한다.
      대용량 운영 쿼리에서는 타입별 함수 또는 정적 SQL로 작성해
      인덱스를 활용할 수 있게 하는 편이 좋다.
	  p_table은 이미 PostgreSQL이 확인한 regclass 객체이므로 %s를 사용합니다.
	  %I: SQL (테이블/컬럼)식별자 << %I는 식별자를 안전하게 인용합니다.
	  테이블에는 %I가 아니라 %s를 쓴 이유는 스키마와 테이블을 적절하게 표현하기위해서 입니다.
	  IS NOT DISTINCT FROM : NULL 컬럼까지 세고 싶을때, NULL끼리도 같은 값으로 처리합니다.
	  $1의 의미 : $1은 함수의 첫 번째 매개변수인 p_table을 의미하지 않습니다. 동적 SQL의 $1은 다음 USING 절에서 전달되는 첫 번째 값을 의미합니다.
    */
    v_sql := format(
        'SELECT count(*) FROM %s 
		 WHERE %I::text 
		 IS NOT DISTINCT FROM 		
		 $1',
        p_table,
        p_column
    );

	RAISE NOTICE '동적 SQL: %', v_sql;	--동적 SQL: SELECT count(*) FROM proc_lab.orders WHERE order_status::text = $1
	RAISE NOTICE '바인딩 값: %', p_value;	--바인딩 값: PENDING


	--실제로는 검색값을 SQL 문자열에 직접 넣지 않고 $1 바인딩 변수로 안전하게 전달합니다.
    EXECUTE v_sql		--만들어진 동적 SQL 실행 
	INTO v_count 		--조회 결과를 변수에 저장
	USING p_value;   	--$1 자리에 값을 안전하게 전달 : 값을 문자열 결합하지 않고 $1 + USING으로 바인딩

    RETURN v_count;
END;
$function$;

