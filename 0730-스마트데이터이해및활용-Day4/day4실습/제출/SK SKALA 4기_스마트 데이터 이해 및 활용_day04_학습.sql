CREATE OR REPLACE PROCEDURE proc_lab.pr_cancel_order(
    IN  p_order_id bigint,
    OUT p_message  text
)
LANGUAGE plpgsql
AS $procedure$
DECLARE
    v_status  proc_lab.orders.order_status%TYPE; --현재 주문 상태
    v_state   text;						--오류 SQLSTATE
    v_message text;						--오류 메시지
    v_detail  text;						--오류 상세정보
    v_context text;						--오류 발생 위치와 호출 문맥

--중첩 블록과 예외 처리
--바깥쪽 BEGIN ... END는 프로시저 본문
BEGIN  
	--안쪽 BEGIN ... END는 별도의 예외 처리 영역입니다.	
    BEGIN  	
		--안쪽 블록에서 예외가 발생하면 안쪽 블록에서 수행했던 변경은 자동으로 취소됩니다.
		--따라서 상품 재고만 복구되고 주문 상태는 변경되지 않는 불완전한 상태를 방지합니다.
		-- 실제 주문 취소 처리영역입니다.


		--주문 조회 및 행 잠금
	--	INTO STRICT : 	
	--		-결과가 반드시 한 건이어야 합니다.
	--		-주문 존재: v_status에 저장
	--		-주문 없음: NO_DATA_FOUND 예외
	--		-여러 건: TOO_MANY_ROWS 예외
        SELECT order_status
          INTO STRICT v_status  --결과가 반드시 한 건이어야 하며,주문번호에 해당하는 현재 상태를 조회하여 v_status에 저장합니다. 예)v_status = PAID
          FROM proc_lab.orders
         WHERE order_id = p_order_id
         FOR UPDATE;  --해당 주문 행을 잠급니다. 예)동시 취소로 재고가 두 번 복구되는 문제를 방지합니다.


		--취소 불가능한 상태 검사
        IF v_status IN ('SHIPPING', 'COMPLETED') THEN
            RAISE EXCEPTION '배송 중(SHIPPING) 또는 주문완료(COMPLETED) 된 주문은 취소할 수 없습니다.'
                USING ERRCODE = 'P0001',   --P0001은 PL/pgSQL에서 일반적으로 사용하는 사용자 정의 예외 코드입니다.
                      DETAIL = format('order_id=%s, status=%s',
                                      p_order_id, v_status);
--			이 예외는 밖으로 바로 전달되지 않고 아래 EXCEPTION 영역에서 처리됩니다.
        END IF;


		--이미 취소된 주문 처리
		--이미 취소된 주문이면 재고 복구와 상태 변경을 실행하지 않고 프로시저를 종료합니다.
		--		첫 번째 호출:
		--		PAID → CANCELLED
		--		재고 2개 복구
		--		
		--		두 번째 호출:
		--		이미 CANCELLED
		--		재고 복구 안 함
		--이 부분이 멱등성을 보장합니다. 같은 취소 요청이 여러 번 전달되어도 최종 상태와 재고가 달라지지 않습니다.
        IF v_status = 'CANCELLED' THEN
            p_message := format('주문 %s는 이미 취소되었습니다.', p_order_id);
            RETURN;  --프로시저를 종료합니다.
        END IF;


		--주문 상품 재고 복구 : 주문 상세에 기록된 수량만큼 상품 재고를 복구합니다.
		--UPDATE ... FROM을 사용해 주문 상품을 한 번에 복구하는 집합 기반 처리입니다.
		--order_items에 다음 고유 제약조건이 있어서 한 상품이 한 행만 존재합니다.
        UPDATE proc_lab.products AS p
           SET stock_qty = p.stock_qty + oi.quantity
          FROM proc_lab.order_items AS oi
         WHERE oi.order_id = p_order_id
           AND oi.product_id = p.product_id;


		--주문 상태 변경
		--주문 상태를 CANCELLED로 변경하고 실제 변경 시각을 기록합니다.
        UPDATE proc_lab.orders
           SET order_status = 'CANCELLED',
               updated_at   = clock_timestamp()  --clock_timestamp()는 실제로 코드가 실행되는 현재 시각을 반환합니다.
         WHERE order_id = p_order_id;


		--상태 변경 이력 저장 : 변경 전후 상태를 이력 테이블에 저장합니다.
        INSERT INTO proc_lab.order_status_history
            (order_id, old_status, new_status)
        VALUES
            (p_order_id, v_status, 'CANCELLED');

		--정상 처리 메시지
        p_message := format('주문 %s 취소 및 재고 복구 완료', p_order_id);

	--안쪽 블록에서 발생한 대부분의 예외를 처리합니다.
    EXCEPTION
        WHEN OTHERS THEN
			-- 오류 처리
			--다음 오류들이 여기에 포함될 수 있습니다.
			--
			--존재하지 않는 주문번호
			--배송 중 또는 완료 주문
			--재고 복구 중 오류
			--주문 상태 변경 오류
			--변경 이력 저장 오류
			--제약조건 위반
			--자료형 오류
            GET STACKED DIAGNOSTICS  --방금 발생한 예외의 상세정보를 변수에 저장합니다.
                v_state   = RETURNED_SQLSTATE,  --오류 코드
                v_message = MESSAGE_TEXT,		--오류 메시지
                v_detail  = PG_EXCEPTION_DETAIL,--추가 오류정보
                v_context = PG_EXCEPTION_CONTEXT;--오류가 발생한 함수·프로시저와 위치
			--GET STACKED DIAGNOSTICS는 반드시 EXCEPTION 처리 영역 안에서 사용해야 합니다.


			--오류 로그 저장 : 오류 정보를 로그 테이블에 저장합니다.
            INSERT INTO proc_lab.routine_error_log
                (routine_name, error_state, error_message,
                 error_detail, error_context)
            VALUES
                ('pr_cancel_order', v_state, v_message,
                 v_detail, v_context);

            -- 오류를 다시 발생시키지 않는 이유:재발생시키지 않으므로 오류 로그가 같은 트랜잭션에서 보존된다.
			-- 호출자는 SQL 오류 대신 메시지를 결과로 받습니다.
            p_message := format('취소 실패 [%s] %s', v_state, v_message);
    END;
END;
$procedure$;


