--참고로 이 함수는 주문 한 건의 영수증을 조회할 때 적합합니다. 
--여러 주문에 대해 반복 호출하면 주문마다 내부 쿼리가 실행되므로, 
--대량 영수증 조회가 필요할 때는 별도의 집합 기반 쿼리를 만드는 것이 더 효율적입니다.


--여러 주문을 한 번에 조회하는 집합 기반 쿼리
--집합 기반으로 구현하려면 주문마다 fn_order_receipt_json()을 반복 호출하지 않고, 
--주문 상세를 order_id별로 한 번에 집계한 다음 주문·고객 테이블과 조인하면 됩니다.
--주문번호 1, 2, 3의 영수증을 한 번에 조회하는 예입니다.
--이 함수는 PL/pgSQL 반복문이 필요 없으므로 LANGUAGE sql로 만들었습니다.
CREATE OR REPLACE FUNCTION proc_lab.fn_order_receipts_json(
    p_order_ids bigint[]
)
RETURNS TABLE (
    receipt_order_id bigint,
    receipt          jsonb
)
LANGUAGE sql
STABLE
STRICT
AS $function$

    WITH target_orders AS MATERIALIZED (	--MATERIALIZED는 조회 대상 주문 집합을 먼저 만들어 재사용하도록 합니다. PostgreSQL 12 이상에서 사용할 수 있습니다.
        SELECT
            o.order_id,
            o.customer_id,
            o.order_status,
            o.ordered_at,
            o.total_amount
        FROM proc_lab.orders AS o
        WHERE o.order_id = ANY (p_order_ids) 	--모든 주문 상품을 주문별로 한 번에 집계 : 반복 실행하지 않고 주문번호별로 상품 배열을 생성합니다.
    ),
    item_json AS (
        SELECT
            oi.order_id,

            jsonb_agg(
                jsonb_build_object(
                    'product_id',   p.product_id,
                    'product_name', p.product_name,
                    'quantity',     oi.quantity,
                    'unit_price',   oi.unit_price,
                    'line_amount',  oi.line_amount
                )
                ORDER BY oi.order_item_id
            ) AS items

        FROM target_orders AS t

        JOIN proc_lab.order_items AS oi
          ON oi.order_id = t.order_id

        JOIN proc_lab.products AS p
          ON p.product_id = oi.product_id

        GROUP BY oi.order_id
    )
    SELECT
        t.order_id AS receipt_order_id,

        jsonb_build_object(
            'order_id',     t.order_id,
            'status',       t.order_status,
            'ordered_at',   t.ordered_at,

            'customer', jsonb_build_object(
                'customer_id', c.customer_id,
                'name',        c.customer_name,
                'email',       c.email
            ),

            'total_amount', t.total_amount,

            'items', coalesce(
                i.items,
                '[]'::jsonb		--상품이 없으면 "items": [] 과 같이 반환합니다.
            )
        ) AS receipt

    FROM target_orders AS t

    JOIN proc_lab.customers AS c
      ON c.customer_id = t.customer_id

    LEFT JOIN item_json AS i		--상품이 없는 주문도 표시 : 상품 목록이 없더라도 주문 자체는 결과에 포함됩니다.
      ON i.order_id = t.order_id

    ORDER BY t.order_id;

$function$;

