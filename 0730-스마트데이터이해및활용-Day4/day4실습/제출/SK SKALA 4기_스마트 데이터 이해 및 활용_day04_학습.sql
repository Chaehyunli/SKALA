-- 07. [중급 함수] %ROWTYPE, SELECT INTO STRICT, 예외 변환
-- ============================================================================

CREATE OR REPLACE FUNCTION proc_lab.fn_find_order(
    p_order_id bigint
)
RETURNS proc_lab.orders
LANGUAGE plpgsql
STABLE
STRICT
AS $function$
DECLARE
    v_order proc_lab.orders%ROWTYPE;
BEGIN
    SELECT o.*
      INTO STRICT v_order
      FROM proc_lab.orders AS o
     WHERE o.order_id = p_order_id;

    RETURN v_order;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE EXCEPTION '주문번호 %를 찾을 수 없습니다.', p_order_id
            USING ERRCODE = 'P0002',
                  HINT = 'orders 테이블의 order_id를 확인하세요.';
END;
$function$;

