CREATE OR REPLACE FUNCTION proc_lab.fn_tax_amount(
    p_amount   numeric,
    p_tax_rate numeric DEFAULT 0.10
)
RETURNS numeric		--numeric형식으로 결과 반환
LANGUAGE sql		--sql로 작성
immutable			--같은 입력값을 전달하면 데이터베이스 상태나 시간에 관계없이 항상 같은 결과를 반환한다는 선언입니다.
strict				--입력값이 NULL이면 함수 본문을 실행하지 않고 NULL 반환
--| 구분          | 같은 입력의 결과        |    테이블 조회 | DML |
--| ----------- | ------------------- | ----------: | --: |
--| `IMMUTABLE` | 항상 동일             | 원칙적으로 부적합 |  불가 |
--| `STABLE`    | 한 SQL 문 안에서 동일   |        가능   |  불가 |
--| `VOLATILE`  | 실행할 때마다 달라질 수 있음 |        가능 |  가능 |
AS $function$
    SELECT round(p_amount * p_tax_rate, 2);
$function$;

COMMENT ON FUNCTION fn_tax_amount(numeric, numeric)
IS '금액과 세율로 세액을 계산하는 순수 계산 함수';

SELECT proc_lab.fn_tax_amount(100000)       AS tax_default_10_percent;
SELECT proc_lab.fn_tax_amount(100000, 0.08) AS tax_8_percent;
SELECT proc_lab.fn_tax_amount(NULL, 0.10)   AS strict_returns_null;


-- ============================================================================
-- 04. [기초 함수] LANGUAGE plpgsql — 변수, IF, 예외 발생
-- ============================================================================

CREATE OR REPLACE FUNCTION proc_lab.fn_line_total(
    p_unit_price       numeric,
    p_quantity         integer,
    p_discount_percent numeric DEFAULT 0
)
RETURNS numeric
LANGUAGE plpgsql
IMMUTABLE
STRICT
AS $function$
DECLARE
    v_subtotal numeric;
    v_result   numeric;
BEGIN
    IF p_unit_price < 0 THEN
        RAISE EXCEPTION '단가는 0 이상이어야 합니다: %', p_unit_price
            USING ERRCODE = '22003';
    END IF;

    IF p_quantity <= 0 THEN
        RAISE EXCEPTION '수량은 1 이상이어야 합니다: %', p_quantity
            USING ERRCODE = '22003';
    END IF;

    IF p_discount_percent NOT BETWEEN 0 AND 100 THEN
        RAISE EXCEPTION '할인율은 0~100 범위여야 합니다: %',
                        p_discount_percent
            USING ERRCODE = '22003';
    END IF;

    v_subtotal := p_unit_price * p_quantity;
    v_result   := v_subtotal * (1 - p_discount_percent / 100.0);

    RETURN round(v_result, 2);
END;
$function$;

SELECT proc_lab.fn_line_total(50000, 2)     AS no_discount;
SELECT proc_lab.fn_line_total(50000, 2, 10) AS discount_10_percent;


-- ============================================================================
-- 05. [중급 함수] 테이블을 조회하여 단일 값 반환
-- ============================================================================

CREATE OR REPLACE FUNCTION proc_lab.fn_customer_order_total(
    p_customer_id bigint
)
RETURNS numeric
LANGUAGE sql
STABLE
STRICT
AS $function$
    SELECT coalesce(sum(o.total_amount), 0)::numeric(14,2)
    FROM proc_lab.orders AS o
    WHERE o.customer_id = p_customer_id
      AND o.order_status <> 'CANCELLED';
$function$;

SELECT c.customer_id,
       c.customer_name,
       proc_lab.fn_customer_order_total(c.customer_id) AS cumulative_order_amount
FROM customers AS c
ORDER BY c.customer_id;


-- ============================================================================
-- 06. [중급 함수] 여러 행 반환 — RETURNS TABLE + RETURN QUERY
-- ============================================================================

CREATE OR REPLACE FUNCTION proc_lab.fn_orders_by_status(
    p_status text DEFAULT NULL
)
RETURNS TABLE (
    order_id      bigint,
    customer_name varchar,
    order_status  varchar,
    total_amount  numeric,
    ordered_at    timestamptz
)
LANGUAGE plpgsql
STABLE
AS $function$
BEGIN
    RETURN QUERY
    SELECT o.order_id,
           c.customer_name,
           o.order_status,
           o.total_amount,
           o.ordered_at
    FROM proc_lab.orders AS o
    JOIN proc_lab.customers AS c
      ON c.customer_id = o.customer_id
    WHERE p_status IS NULL
       OR o.order_status = p_status
    ORDER BY o.ordered_at DESC;
END;
$function$;

