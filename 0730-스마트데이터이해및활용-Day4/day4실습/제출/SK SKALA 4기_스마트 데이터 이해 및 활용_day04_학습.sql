--상품번호: 2
--주문수량: 2개
--주문번호: 처음에는 모르므로 NULL
--주문이 등록되면 새 주문번호가 p_order_id에 저장됨

SELECT *
FROM orders
ORDER BY order_id DESC
LIMIT 3;


