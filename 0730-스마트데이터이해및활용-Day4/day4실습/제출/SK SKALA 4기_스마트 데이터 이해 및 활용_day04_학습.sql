-- ============================================================================
-- 08. [중급 함수] 함수도 DML 가능 — 재고 차감 후 남은 수량 반환
-- ============================================================================

CREATE OR REPLACE FUNCTION proc_lab.fn_reserve_stock(
    p_product_id bigint,
    p_quantity   integer
)
RETURNS integer
LANGUAGE plpgsql
VOLATILE
STRICT
AS $function$
DECLARE
    v_remaining integer;
BEGIN
    IF p_quantity <= 0 THEN
        RAISE EXCEPTION '차감 수량은 1 이상이어야 합니다.'
            USING ERRCODE = '22003';
    END IF;

    UPDATE proc_lab.products
       SET stock_qty = stock_qty - p_quantity
     WHERE product_id = p_product_id
       AND active
       AND stock_qty >= p_quantity
    RETURNING stock_qty INTO v_remaining;

    IF NOT FOUND THEN
        RAISE EXCEPTION '상품 %의 재고가 부족하거나 비활성 상태입니다.',
                        p_product_id
            USING ERRCODE = 'P0001';
    END IF;

    RETURN v_remaining;
END;
$function$;

SELECT proc_lab.fn_reserve_stock(5, 50) AS remaining_stock;
SELECT product_id, product_name, stock_qty
FROM products
WHERE product_id = 1;


-- ============================================================================
-- 09. [기초 프로시저] 주문 생성 — CALL + INOUT
-- ============================================================================
--고객이 상품을 주문하면 상품 가격과 재고를 확인하고, 
--재고를 차감한 뒤 주문 헤더와 주문 상세를 생성하여 
--새 주문번호를 돌려주는 프로시저입니다.
--| 매개변수            | 모드      | 의미                         |
--| --------------- | ------- | -------------------------- |
--| `p_customer_id` | `IN`    | 주문할 고객번호                   |
--| `p_product_id`  | `IN`    | 주문할 상품번호                   |
--| `p_quantity`    | `IN`    | 주문수량                       |
--| `p_order_id`    | `INOUT` | 호출할 때 값을 받고, 처리 후 주문번호를 반환 |

CREATE OR REPLACE PROCEDURE proc_lab.pr_create_order(
    IN    p_customer_id bigint,
    IN    p_product_id  bigint,
    IN    p_quantity    integer,
    INOUT p_order_id    bigint DEFAULT NULL
)
LANGUAGE plpgsql
AS $procedure$
DECLARE
    v_unit_price products.unit_price%TYPE; --상품 단가를 저장하는 지역변수
BEGIN
	RAISE NOTICE '고객번호: %', p_customer_id;
	RAISE NOTICE '상품번호: %', p_product_id;
	RAISE NOTICE '주문수량: %', p_quantity;
	--주문수량 검증
    IF p_quantity <= 0 THEN
        RAISE EXCEPTION '주문 수량은 1 이상이어야 합니다.'
            USING ERRCODE = '22003';
    END IF;

	--주문할 상품의 단가 조회
    SELECT p.unit_price
      INTO STRICT v_unit_price   --조회된 상품 가격은 v_unit_price에 저장됩니다.STRICT가 있기 때문에 반드시 한 건이 조회되어야 합니다
      FROM proc_lab.products AS p
     WHERE p.product_id = p_product_id
       AND p.active;
	RAISE NOTICE '상품단가: %', v_unit_price;

    -- 함수가 DML을 수행하고 남은 재고를 반환한다.
	-- fn_reserve_stock() 함수를 호출하여 재고를 예약하거나 차감합니다.
	-- PERFORM은 PL/pgSQL에서 함수의 반환값을 사용하지 않고 함수만 실행할 때 사용합니다.
    PERFORM proc_lab.fn_reserve_stock(p_product_id, p_quantity);

	--주문 헤더 생성
	--orders 테이블에 주문의 기본 정보를 입력합니다.
    INSERT INTO proc_lab.orders (customer_id, order_status, total_amount)
    VALUES (
        p_customer_id,
        'PENDING',
        proc_lab.fn_line_total(v_unit_price, p_quantity) --할인처리함수호출
    )
    RETURNING order_id INTO p_order_id;
	--RETURNING의 역할 : 새롭게 생성된 주문번호를 바로 받아옵니다.예)p_order_id = 15
	-- 별도로 다시 조회할 필요가 없습니다.


	--order_items 테이블에 주문한 상품의 상세 내용을 입력합니다.
--	현재 프로시저는 상품번호를 하나만 받기 때문에 한 번 호출할 때 한 종류의 상품만 주문할 수 있는 구조입니다.
--	order_id   = 15
--	product_id = 2
--	quantity   = 2
--	unit_price = 50000
    INSERT INTO proc_lab.order_items
        (order_id, product_id, quantity, unit_price)
    VALUES
        (p_order_id, p_product_id, p_quantity, v_unit_price);

--	주문번호 출력 : % 자리에 p_order_id 값이 들어갑니다.
    RAISE NOTICE '새 주문번호: %', p_order_id;
END;
$procedure$;

--프로시저를 proc_lab 스키마에 확실히 만들려면 선언과 호출도 다음처럼 스키마를 지정하는 것이 안전합니다.
CALL proc_lab.pr_create_order(1, 2, 2, NULL);
