CREATE OR REPLACE PROCEDURE pr_restock_low_inventory(
    IN  p_threshold integer,		--재고 부족 판단 기준
    IN  p_add_qty   integer,		--상품마다 추가할 재고
    OUT p_affected  integer			--재고를 보충한 상품 개수  <<OUT 매개변수 자리
)
LANGUAGE plpgsql
AS $procedure$
DECLARE
    v_product products%ROWTYPE; --products 테이블의 한 행 전체를 저장할 수 있는 변수입니다.
--다음처럼 모든 컬럼을 사용할 수 있습니다.
--v_product.product_id
--v_product.product_name
--v_product.stock_qty
--v_product.unit_price
--v_product.active
BEGIN
--입력값 검증
    IF p_threshold < 0 OR p_add_qty <= 0 THEN
        RAISE EXCEPTION '기준 재고는 0 이상, 추가 수량은 1 이상이어야 합니다.';
    END IF;

--NULL 검증 보완
	IF p_threshold IS NULL
	   OR p_add_qty IS NULL
	   OR p_threshold < 0
	   OR p_add_qty <= 0 THEN
	
	    RAISE EXCEPTION
	        '기준 재고는 0 이상, 추가 수량은 1 이상이어야 합니다.'
	        USING ERRCODE = '22023';
	END IF;

    p_affected := 0; --처리 건수 초기화 : 재고를 보충한 상품 수를 저장할 출력 매개변수를 0으로 초기화합니다.


--재고 부족 상품 조회
    FOR v_product IN
        SELECT *
        FROM proc_lab.products
        WHERE active    -- active = true 와 같은 표현으로 활성 상품만 대상으로 합니다.
          AND stock_qty < p_threshold		--현재 재고가 기준치보다 작은 상품만 조회합니다.
        ORDER BY product_id				--상품번호 순서로 처리합니다.
        FOR UPDATE		--조회한 상품 행을 잠급니다.재고처럼 동시 변경 가능성이 높은 데이터에서는 중요한 처리입니다.
    LOOP
        UPDATE proc_lab.products
           SET stock_qty = stock_qty + p_add_qty		--상품별 재고 증가
         WHERE product_id = v_product.product_id;	--v_product.product_id는 현재 반복 중인 상품번호입니다.

        p_affected := p_affected + 1;		--상품 하나를 처리할 때마다 출력값을 1씩 증가시킵니다.
		RAISE NOTICE '처리: % 건',
                     p_affected;

        RAISE NOTICE '% 재고 보충: % → %',
                     v_product.product_name,
                     v_product.stock_qty,
                     v_product.stock_qty + p_add_qty;
    END LOOP;
END;
$procedure$;


--활성 상품 중 재고가 기준치보다 적은 상품을 찾아, 각 상품의 재고를 지정한 수량만큼 추가하고 
--처리한 상품 개수를 반환합니다.
--현재 재고가 70개 미만
--활성 상태인 상품을 찾아
--상품마다 재고 20개 추가
--처리한 상품 수를 p_affected로 반환
CALL pr_restock_low_inventory(70, 20, NULL);

-- 단순히 같은 값을 일괄 변경한다면 반복문보다 아래와 같은 집합 기반 UPDATE가 좋다.
