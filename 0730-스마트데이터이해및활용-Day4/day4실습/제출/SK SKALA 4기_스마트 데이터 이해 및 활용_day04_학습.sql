-- 13. [중급 프로시저] 집합 기반 배치 — 가격 일괄 할인
-- ============================================================================

CREATE OR REPLACE PROCEDURE proc_lab.pr_bulk_discount(
    IN  p_discount_percent numeric,  	--상품에 적용할 할인율
    IN  p_min_price        numeric,		--할인 대상이 되는 최소 가격
    OUT p_affected         integer		--가격이 변경된 상품 개수
)
LANGUAGE plpgsql
AS $procedure$
BEGIN
--NULL과 할인율 유효성 검사 : 할인율은 0% 초과 50% 이하만 허용합니다.
    IF p_discount_percent IS NULL
	   OR p_discount_percent <= 0
	   OR p_discount_percent > 50 THEN
	    RAISE EXCEPTION
	        '배치 할인율은 0 초과 50 이하이어야 합니다.'
	        USING ERRCODE = '22023';
	END IF;

--NULL과 최소 가격 검증 보완
	IF p_min_price IS NULL OR p_min_price < 0 THEN
        RAISE EXCEPTION
            '최소 가격은 0 이상이어야 합니다.'
            USING ERRCODE = '22023';
    END IF;

--상품 가격 일괄 변경 : 반복문 없이 조건에 맞는 모든 상품 가격을 한 번의 UPDATE로 변경합니다.
    UPDATE proc_lab.products
       SET unit_price = round(
           unit_price * (1 - p_discount_percent / 100.0),
           2
       )
     WHERE active = true  --비활성 상품은 가격을 변경하지 않습니다.
       AND unit_price >= p_min_price;

-- GET DIAGNOSTICS : 위에 업데이트쿼리와 아래 사이에 다른 쿼리가 들어오면 그 처리 행 개수를 반환할 수 있으니 주의하세요
    GET DIAGNOSTICS p_affected = ROW_COUNT; --바로 전에 실행한 UPDATE가 처리한 행 개수를 가져옵니다.
END;
$procedure$;

--활성 상품 중 가격이 기준 금액 이상인 모든 상품에 동일한 할인율을 한꺼번에 적용하고, 변경된 상품 개수를 반환합니다.
--할인율: 5%
--할인 대상: 가격이 100,000원 이상
--활성 상품만 처리
--처리한 상품 개수를 p_affected로 반환
CALL proc_lab.pr_bulk_discount(5, 100000, NULL); --1.멱등성 처리없는 프로시저 호출

SELECT product_id, product_name, unit_price,stock_qty,active FROM products ORDER BY product_id;


--2. 멱등성 적용 프로시저
--기존 프로시저와 혼동하지 않도록 새로운 이름으로 작성했습니다.
CREATE OR REPLACE PROCEDURE proc_lab.pr_bulk_discount_idempotent(
    IN  p_batch_key        text,
    IN  p_discount_percent numeric,
    IN  p_min_price        numeric,
    OUT p_affected         integer
)
LANGUAGE plpgsql
AS $procedure$
DECLARE
    v_batch_key      text;
    v_claimed        integer;
    v_saved_discount numeric;
    v_saved_min_price numeric;
    v_saved_affected integer;
    v_saved_status   text;
BEGIN
    ----------------------------------------------------------------
    -- 1. 입력값 정리 및 검증
    ----------------------------------------------------------------
    v_batch_key := btrim(p_batch_key);

    IF v_batch_key IS NULL OR v_batch_key = '' THEN
        RAISE EXCEPTION '배치 키는 필수입니다.'
            USING ERRCODE = '23502';
    END IF;

    IF p_discount_percent IS NULL
       OR p_discount_percent <= 0
       OR p_discount_percent > 50 THEN
        RAISE EXCEPTION
            '배치 할인율은 0 초과 50 이하이어야 합니다.'
            USING ERRCODE = '22023';
    END IF;

    IF p_min_price IS NULL OR p_min_price < 0 THEN
        RAISE EXCEPTION
            '최소 가격은 0 이상이어야 합니다.'
            USING ERRCODE = '22023';
    END IF;

    ----------------------------------------------------------------
    -- 2. 배치 키 선점
    --    동일한 배치 키가 없을 때만 1건 INSERT된다.
    ----------------------------------------------------------------
    INSERT INTO proc_lab.bulk_discount_runs (
        batch_key,
        discount_percent,
        min_price,
        affected_count,
        run_status
    )
    VALUES (
        v_batch_key,
        p_discount_percent,
        p_min_price,
        0,
        'PROCESSING'
    )
    ON CONFLICT (batch_key)
    DO NOTHING;

    GET DIAGNOSTICS v_claimed = ROW_COUNT;

    ----------------------------------------------------------------
    -- 3. 이미 존재하는 배치 키이면 기존 실행 결과 반환
    ----------------------------------------------------------------
    IF v_claimed = 0 THEN
        SELECT
            discount_percent,
            min_price,
            affected_count,
            run_status
        INTO STRICT
            v_saved_discount,
            v_saved_min_price,
            v_saved_affected,
            v_saved_status
        FROM proc_lab.bulk_discount_runs
        WHERE batch_key = v_batch_key
        FOR UPDATE;

        -- 같은 배치 키를 다른 조건으로 사용하지 못하게 검사
--		기존에는 할인율 5%로 사용한 배치 키인데 10%로 다시 요청하면 오류가 발생합니다.
        IF v_saved_discount IS DISTINCT FROM p_discount_percent
           OR v_saved_min_price IS DISTINCT FROM p_min_price THEN
            RAISE EXCEPTION
                '배치 키 %는 이미 다른 조건으로 사용되었습니다. 기존 할인율=%, 기존 최소가격=%',
                v_batch_key,
                v_saved_discount,
                v_saved_min_price
                USING ERRCODE = '22023';
        END IF;

        IF v_saved_status = 'COMPLETED' THEN
            p_affected := v_saved_affected;
			--멱등성 요청에서는 재실행 때 0을 반환하기보다 최초 실행 결과와 같은 결과를 반환하는 방식이 일반적입니다.
            RAISE NOTICE
                '배치 %는 이미 완료되었습니다. 할인을 다시 적용하지 않습니다. 기존 처리 건수=%',
                v_batch_key,
                p_affected;

            RETURN;
        END IF;

        RAISE EXCEPTION
            '배치 %가 현재 처리 중입니다.',
            v_batch_key;
    END IF;

    ----------------------------------------------------------------
    -- 4. 최초 요청일 때만 실제 할인 적용
    ----------------------------------------------------------------
    UPDATE proc_lab.products
       SET unit_price = round(
           unit_price
           * (1 - p_discount_percent / 100.0),
           2
       )
     WHERE active
       AND unit_price >= p_min_price;

    GET DIAGNOSTICS p_affected = ROW_COUNT;

    ----------------------------------------------------------------
    -- 5. 배치 실행 완료 기록
    ----------------------------------------------------------------
    UPDATE proc_lab.bulk_discount_runs
       SET affected_count = p_affected,
           run_status     = 'COMPLETED',
           completed_at   = clock_timestamp()
     WHERE batch_key = v_batch_key;

    RAISE NOTICE
        '배치 % 할인 완료: 할인율=%, 최소가격=%, 처리건수=%',
        v_batch_key,
        p_discount_percent::text || '%',
        p_min_price,
        p_affected;
END;
$procedure$;

--멱등성 적용 프로시저 호출
--할인 도중 오류가 발생하면 상품 가격 변경과 배치 실행 기록이 같은 트랜잭션에서 함께 롤백됩니다.
CALL proc_lab.pr_bulk_discount_idempotent(
    'SALE-20260725-001',
    5,
    100000,
    NULL
);
--실행 이력 확인
SELECT
    batch_key,
    discount_percent,
    min_price,
    affected_count,
    run_status,
    started_at,
    completed_at
FROM proc_lab.bulk_discount_runs
ORDER BY started_at DESC;

