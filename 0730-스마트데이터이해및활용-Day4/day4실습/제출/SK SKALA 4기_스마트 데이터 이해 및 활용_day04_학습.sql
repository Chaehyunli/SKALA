CREATE OR REPLACE PROCEDURE proc_lab.pr_upsert_customer(
    IN    p_customer_name  varchar,		--등록하거나 수정할 고객명
    IN    p_email          varchar,		--고객을 식별하는 이메일
    INOUT p_customer_id    bigint DEFAULT null	--신규 또는 기존 고객번호 반환
)
LANGUAGE plpgsql
AS $procedure$
BEGIN
--고객명 필수 검사 : nullif()>> NULL차단,btrim()의 역할 >> 문자열 양쪽의 공백을 제거합니다.
    IF nullif(btrim(p_customer_name), '') IS NULL THEN
        RAISE EXCEPTION '고객명은 필수입니다.'
            USING ERRCODE = '23502';
    END IF;


--이메일 형식 검사
--PostgreSQL 정규표현식 연산자입니다.
--| 연산자   | 의미                |
--| ----- | ----------------- |
--| `~`   | 대소문자를 구분하여 일치     |
--| `~*`  | 대소문자를 구분하지 않고 일치  |
--| `!~`  | 대소문자를 구분하여 불일치    |
--| `!~*` | 대소문자를 구분하지 않고 불일치 |

--| 표현식              | 정규표현식 해석     |
--| ---------------- | --------------- |
--| `^`              | 문자열 시작          |
--| `[A-Z0-9._%+-]+` | 이메일 아이디 부분      |
--| `@`              | @ 문자            |
--| `[A-Z0-9.-]+`    | 도메인 부분          |
--| `\.`             | 점 문자            |
--| `[A-Z]{2,}`      | 2글자 이상의 최상위 도메인 |
--| `$`              | 문자열 끝           |
	
	IF nullif(btrim(p_email), '') IS NULL THEN
	    RAISE EXCEPTION '이메일은 필수입니다.'
	        USING ERRCODE = '23502';
	END IF;
	
	IF btrim(p_email) !~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$' THEN
        RAISE EXCEPTION '올바른 이메일 형식이 아닙니다: %', p_email
            USING ERRCODE = '22023';
    END IF;

--같은 이메일이 없으면 INSERT, 이미 있으면 UPDATE하고 고객번호를 반환합니다.
--EXCLUDED는 원래 INSERT하려고 했지만 중복으로 인해 제외된 새로운 데이터를 의미합니다.
    INSERT INTO proc_lab.customers (customer_name, email)
    VALUES (btrim(p_customer_name), btrim(p_email))
    ON CONFLICT (email_normalized) 		--email_normalized 값이 중복되면 INSERT하지 않고 DO UPDATE를 실행합니다.
    DO UPDATE
       SET customer_name = EXCLUDED.customer_name,
           email         = EXCLUDED.email,
           active        = true		--기존 고객이 탈퇴 또는 비활성 상태여도 같은 이메일로 다시 등록하면 활성 고객으로 복구합니다.
    RETURNING customer_id INTO p_customer_id;
END;
$procedure$;

--이 프로시저는 고객 이메일을 기준으로 고객을 신규 등록하거나, 이미 존재하면 고객정보를 수정하는 UPSERT 프로시저입니다.
CALL proc_lab.pr_upsert_customer('한지민', 'jimin@example.com', NULL);
CALL proc_lab.pr_upsert_customer('한지민(수정)', 'JIMIN@example.com', NULL);
