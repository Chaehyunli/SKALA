-- 10. [중급 프로시저] 상태 변경 — OUT 매개변수 + GET DIAGNOSTICS
-- ============================================================================

CREATE OR REPLACE PROCEDURE pr_change_order_status(
    IN  p_order_id   bigint,  	--상태를 변경할 주문번호 3
    IN  p_new_status text,		--새롭게 적용할 주문 상태 PAID
    OUT p_message    text		--처리 결과 메시지 반환 NULL
)
LANGUAGE plpgsql
AS $procedure$
DECLARE
    v_old_status orders.order_status%TYPE; --지역변수 선언 : 변경 전 주문 상태를 저장합니다.
    v_row_count  integer;  	--UPDATE로 실제 변경된 행의 개수를 저장(0,1)
BEGIN
--다음 다섯 가지 상태만 허용합니다.
--PENDING   : 주문 대기
--PAID      : 결제 완료
--SHIPPING  : 배송 중
--COMPLETED : 주문 완료
--CANCELLED : 주문 취소
    IF p_new_status IS NULL
	   OR p_new_status NOT IN
	      ('PENDING', 'PAID', 'SHIPPING', 'COMPLETED', 'CANCELLED') THEN
	    RAISE EXCEPTION '허용되지 않은 주문 상태입니다: %',
	                    COALESCE(p_new_status, 'NULL')
	        USING ERRCODE = '22023';
	END IF;

--  현재 주문 상태 조회
    SELECT order_status
      INTO STRICT v_old_status   --주문번호에 해당하는 현재 상태를 조회해서 v_old_status에 저장합니다.
      FROM proc_lab.orders
     WHERE order_id = p_order_id
     FOR UPDATE;  --조회한 주문 행을 잠급니다. 잠금은 일반적으로 트랜잭션이 COMMIT 또는 ROLLBACK될 때 해제됩니다.
--INTO STRICT : 조회 결과가 반드시 한 건이어야 한다는 뜻입니다.
--
--조회 결과 1건: 정상적으로 변수에 저장
--조회 결과 0건: NO_DATA_FOUND 오류
--조회 결과 2건 이상: TOO_MANY_ROWS 오류
--
--order_id가 기본키라면 여러 건이 조회될 가능성은 없으므로, 주로 존재하지 않는 주문번호를 검사하는 효과가 있습니다.


--주문 상태 변경 - 주문 상태와 수정 시간을 변경합니다.
--clock_timestamp()와 now() 차이
--now(): 현재 트랜잭션이 시작된 시각
--clock_timestamp(): 함수가 호출되는 실제 현재 시각
--
--프로시저 내부 작업의 정확한 실행 시각을 기록하려면 clock_timestamp()가 적합합니다.
    UPDATE proc_lab.orders
       SET order_status = p_new_status,   --새로운 주문 상태를 저장합니다.
           updated_at   = clock_timestamp()   --실제로 UPDATE가 실행되는 현재 시각을 기록합니다.
     WHERE order_id = p_order_id
       AND order_status IS DISTINCT FROM p_new_status; --기존 상태와 새 상태가 다를 때만 UPDATE합니다.
								--예를 들어:기존 상태 PENDING, 새 상태 PAID → 서로 다름 → UPDATE 실행
								--<>와 비슷하지만 NULL까지 안전하게 비교할 수 있다는 차이가 있습니다.

--UPDATE된 행 개수 확인
    GET DIAGNOSTICS v_row_count = ROW_COUNT;

	RAISE NOTICE '변경 전 상태: %', v_old_status;
	RAISE NOTICE '변경 요청 상태: %', p_new_status;
	RAISE NOTICE 'UPDATE 행 개수: %', v_row_count;

    IF v_row_count = 0 THEN
        p_message := format('주문 %s는 이미 %s 상태입니다.',
                            p_order_id, p_new_status);
        RETURN;
    END IF;



    INSERT INTO proc_lab.order_status_history
        (order_id, old_status, new_status)
    VALUES
        (p_order_id, v_old_status, p_new_status);

    p_message := format('주문 %s: %s → %s 변경 완료',
                        p_order_id, v_old_status, p_new_status);
END;
$procedure$;

--주문 상태를 변경하고, 실제로 상태가 변경된 경우에만 변경 이력을 저장한 뒤 처리 결과 메시지를 반환합니다.
-- OUT 매개변수 자리에는 SQL에서 보통 NULL을 전달한다.
