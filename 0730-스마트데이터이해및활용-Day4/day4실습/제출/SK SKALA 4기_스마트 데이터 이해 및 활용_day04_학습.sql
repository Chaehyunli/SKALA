-- ============================================================================
-- 15. [고급 함수] JSONB 영수증 반환
-- ============================================================================
--이 함수는 주문번호 하나를 받아 주문 정보, 고객 정보, 주문 상품 목록을 
--하나의 중첩된 JSONB 영수증으로 만들어 반환합니다.
CREATE OR REPLACE FUNCTION proc_lab.fn_order_receipt_json(
    p_order_id bigint			--조회할 주문번호
)
RETURNS jsonb					--JSONB 형식으로 결과 반환
LANGUAGE plpgsql				--PL/pgSQL로 작성
stable							--같은 SQL 문 안에서는 안정적인 조회 결과 : 영수증 조회 함수
--이 함수는 테이블 데이터가 변경되면 결과도 달라지므로 IMMUTABLE은 적합하지 않고 STABLE이 적합합니다.
--따라서 NULL 주문번호에 대해 예외를 발생시키고 싶다면 STRICT를 제거하고 함수 본문에서 직접 검사해야 합니다.
strict							--입력값이 NULL이면 함수 본문을 실행하지 않고 NULL 반환
AS $function$
DECLARE
    v_result jsonb;  --결과 저장 변수 : 최종으로 만들어진 JSONB 영수증을 저장하는 지역변수입니다.
BEGIN
	--{K:V,{K:V}} : 이런 구조를 중첩 JSON 객체라고 합니다.
	--jsonb_build_object()는 키와 값을 번갈아 작성해 JSONB 객체를 만듭니다.
    SELECT jsonb_build_object(
        'order_id',      o.order_id,
        'status',        o.order_status,
        'ordered_at',    o.ordered_at,			--날짜와 시간은 JSON에서 문자열 형태로 표현됩니다.
        'customer',      jsonb_build_object(	--고객 정보를 중첩 객체로 생성 : 고객 정보는 최상위에 평평하게 넣지 않고 customer라는 하위 객체로 묶습니다.
                             'customer_id', c.customer_id,
                             'name',        c.customer_name,
                             'email',       c.email
                         ),
        'total_amount',  o.total_amount,		--JSONB에서 숫자는 숫자 형식으로 유지됩니다.
        'items',         coalesce(				--주문 상품 배열 생성
            (
                SELECT jsonb_agg(				--jsonb_agg()로 배열 생성 : 각 주문 상품 객체를 하나의 배열로 합칩니다. 예: [{},{}]
                    jsonb_build_object(			--상품 하나(주문 상세 한 행)를 JSON 객체로 변환
                        'product_id',   p.product_id,
                        'product_name', p.product_name,
                        'quantity',     oi.quantity,
                        'unit_price',   oi.unit_price,	--unit_price를 현재 products.unit_price가 아니라 order_items.unit_price에서 가져오는 점이 중요합니다.상품 가격이 나중에 변경돼도 주문 당시 단가를 영수증에 표시할 수 있습니다.
                        'line_amount',  oi.line_amount
                    )
                    ORDER BY oi.order_item_id		--주문 상세번호 순서로 배열 요소를 정렬합니다.JSONB 객체의 키 순서는 보장되지 않지만 items 배열의 상품 순서는 이 ORDER BY에 의해 유지됩니다.
                )
                FROM proc_lab.order_items AS oi		--주문과 상품 JOIN
                JOIN proc_lab.products AS p			--INNER JOIN이므로 연결된 상품이 없는 주문은 조회되지 않습니다.
                  ON p.product_id = oi.product_id
                WHERE oi.order_id = o.order_id		--상관 서브쿼리 : 내부 쿼리에서 외부 쿼리의 o.order_id를 사용하므로 상관 서브쿼리입니다.
            ),
            '[]'::jsonb		--주문 상품이 없을 때 빈 배열 반환 : items: null 보다 items: [] 가 애플리케이션에서 처리하기 편합니다.
        )
    )
      INTO v_result		--주문번호에 해당하는 행이 없으면 SELECT INTO 결과가 없으므로 v_result는 NULL이 됩니다.
      FROM proc_lab.orders AS o					--주문과 고객 JOIN
      JOIN proc_lab.customers AS c				--INNER JOIN이므로 연결된 고객이 없는 주문은 조회되지 않습니다.
        ON c.customer_id = o.customer_id		--주문의 고객번호를 이용해 고객정보를 가져옵니다.
     WHERE o.order_id = p_order_id;				--주문번호로 주문을 찾고, 

	--주문이 없는 경우 : P0002는 PL/pgSQL의 NO_DATA_FOUND에 해당하는 SQLSTATE입니다.
	--현재 코드에서는 INTO STRICT를 사용하지 않고 직접 검사하기 때문에 사용자에게 이해하기 쉬운 오류 메시지를 제공할 수 있습니다.
    IF v_result IS NULL THEN
        RAISE EXCEPTION '주문번호 %를 찾을 수 없습니다.', p_order_id
            USING ERRCODE = 'P0002';
    END IF;

    RETURN v_result;	--JSONB 반환 : {"items":[...],"status":"PAID","order_id":1,...}
END;
$function$;

