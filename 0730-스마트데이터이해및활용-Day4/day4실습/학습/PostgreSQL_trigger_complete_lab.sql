/*
===============================================================================
 26. 핵심 요약
===============================================================================

 1. PostgreSQL 트리거는 트리거 함수와 함께 동작한다.

 2. BEFORE 트리거는 저장 전에 NEW를 검증하거나 변경할 때 적합하다.

 3. AFTER 트리거는 감사 로그와 후속 작업에 적합하다.

 4. INSTEAD OF 트리거는 주로 뷰의 작업을 대신 처리한다.

 5. FOR EACH ROW는 행마다 실행되고,
    FOR EACH STATEMENT는 SQL 문장마다 한 번 실행된다.

 6. INSERT는 NEW, DELETE는 OLD, UPDATE는 NEW와 OLD를 사용한다.

 7. BEFORE 행 트리거에서 RETURN NULL은 해당 행 작업을 건너뛴다.
    AFTER 트리거의 반환값은 원본 행에 영향을 주지 않는다.

 8. 벌크 INSERT에서도 행 단위 트리거는 입력 행 수만큼 실행된다.
    COPY FROM도 트리거와 제약조건을 실행한다.

 9. 문장 단위 트리거와 전환 테이블을 사용하면
    변경된 여러 행을 집합 기반으로 처리할 수 있다.

10. 트리거와 원본 SQL은 같은 트랜잭션에 참여한다.
    트리거 오류 또는 ROLLBACK은 원본 작업과 트리거 작업 모두에 영향을 준다.

11. 단순한 무결성 규칙은 CHECK, UNIQUE, FOREIGN KEY 같은
    선언적 제약조건을 우선 사용한다.

12. 트리거는 편리하지만 자동으로 숨어서 실행되므로
    성능, 재귀, 실행 순서, 권한, 운영 가시성을 함께 고려해야 한다.

===============================================================================
*/
