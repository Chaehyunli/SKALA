===============================================================================
 0. 핵심 개념
===============================================================================

 트리거(trigger)는 테이블이나 뷰에서 특정 사건이 발생했을 때
 PostgreSQL이 지정된 함수를 자동으로 실행하게 하는 데이터베이스 객체다.

   INSERT / UPDATE / DELETE / TRUNCATE 발생
                        ↓
                  트리거가 감지
                        ↓
                  트리거 함수 실행

 PostgreSQL 트리거는 다음 두 객체로 구성된다.

   1) 트리거 함수
      - 실제로 수행할 작업을 작성한다.
      - 일반적으로 PL/pgSQL로 작성한다.
      - 일반 매개변수를 선언하지 않는다.
      - 반드시 RETURNS trigger로 선언한다.

   2) 트리거
      - 언제 실행할지 지정한다.
      - 어떤 사건에서 실행할지 지정한다.
      - 행마다 실행할지, 문장마다 실행할지 지정한다.
      - 실행할 트리거 함수를 연결한다.

 트리거를 이해하는 세 가지 기준

   실행 시점 : BEFORE / AFTER / INSTEAD OF
   실행 사건 : INSERT / UPDATE / DELETE / TRUNCATE
   실행 단위 : ROW / STATEMENT

 PostgreSQL은 MySQL처럼 CREATE TRIGGER 문 안에 처리 SQL을 직접 작성하지 않는다.
 트리거 정의는 실행할 트리거 함수를 참조해야 한다.

 CREATE TRIGGER 문에서 과거 문법인 EXECUTE PROCEDURE를 허용하는 버전도 있지만
 실제 대상은 프로시저가 아니라 함수다. 현재는 EXECUTE FUNCTION을 사용한다.

 트리거와 트리거가 호출한 함수는 원본 SQL과 같은 트랜잭션에 참여한다.
 따라서 트리거에서 오류가 발생하면 원본 INSERT, UPDATE, DELETE도 롤백된다.
*/


