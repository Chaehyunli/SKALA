-- IDENTITY 열에 명시적인 ID를 넣었으므로 다음 자동 번호를 최댓값 뒤로 이동한다.
--운영 중 수시로 실행하는 코드가 아니라, 명시적 ID 입력이나 데이터 이관이 끝난 직후 한 번 실행하는 동기화 코드입니다.
---ex)---------------------------------------
--| 테이블       | 현재 최대 ID | 다음 자동 ID |
--| ---------- | -------:   | -------:  |
--| customers  |      100   |      101  |
--| products   |       50   |       51  |
--| orders     |    1,000   |    1,001  |

SELECT setval(
           pg_get_serial_sequence('proc_lab.customers', 'customer_id'),
           (SELECT max(customer_id) FROM customers),
           true			--최댓값이 이미 테이블에 존재(5)하는 현재 상황에서는 반드시 true가 적절합니다.
       );

SELECT setval(
           pg_get_serial_sequence('proc_lab.products', 'product_id'),
           (SELECT max(product_id) FROM products),
           true			--최댓값이 이미 테이블에 존재(5)하는 현재 상황에서는 반드시 true가 적절합니다.
       );

SELECT setval(
           pg_get_serial_sequence('proc_lab.orders', 'order_id'),
           (SELECT max(order_id) FROM orders),
           true			--최댓값이 이미 테이블에 존재(5)하는 현재 상황에서는 반드시 true가 적절합니다.
       );

