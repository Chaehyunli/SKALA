-- ============================================================================
-- 01. 테이블 생성 — 주문관리 업무 모델
-- ============================================================================

CREATE TABLE customers (
    customer_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name    varchar(100) NOT NULL,
    email            varchar(200) NOT NULL,
    email_normalized text GENERATED ALWAYS AS (lower(email)) STORED UNIQUE,
    customer_grade   varchar(10) NOT NULL DEFAULT 'BASIC'
                     CHECK (customer_grade IN ('BASIC', 'SILVER', 'GOLD', 'VIP')),
    active            boolean NOT NULL DEFAULT true,
    created_at        timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE products (
    product_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name  varchar(120) NOT NULL,
    unit_price    numeric(12,2) NOT NULL CHECK (unit_price >= 0),
    stock_qty     integer NOT NULL DEFAULT 0 CHECK (stock_qty >= 0),
    active        boolean NOT NULL DEFAULT true,
    created_at    timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE orders (
    order_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   bigint NOT NULL REFERENCES customers(customer_id),
    order_status  varchar(20) NOT NULL DEFAULT 'PENDING'
                  CHECK (order_status IN
                         ('PENDING', 'PAID', 'SHIPPING', 'COMPLETED', 'CANCELLED')),
    total_amount  numeric(14,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    note          text,
    ordered_at    timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at    timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE order_items (
    order_item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      bigint NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    product_id    bigint NOT NULL REFERENCES products(product_id),
    quantity      integer NOT NULL CHECK (quantity > 0),
    unit_price    numeric(12,2) NOT NULL CHECK (unit_price >= 0),
    line_amount   numeric(14,2)
                  GENERATED ALWAYS AS (quantity * unit_price) STORED,
    UNIQUE (order_id, product_id)
);

CREATE TABLE order_status_history (
    history_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     bigint NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    old_status   varchar(20),
    new_status   varchar(20) NOT NULL,
    changed_by   text NOT NULL DEFAULT current_user,
    changed_at   timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE audit_log (
    audit_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name   text NOT NULL,
    operation    text NOT NULL,
    row_id       bigint,
    old_data     jsonb,
    new_data     jsonb,
    changed_by   text NOT NULL DEFAULT current_user,
    changed_at   timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE routine_error_log (
    log_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    routine_name   text NOT NULL,
    error_state    text,
    error_message  text,
    error_detail   text,
    error_context  text,
    created_at     timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE transaction_demo_log (
    log_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message     text NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT clock_timestamp()
);


--디스카운트 이벤트시에 멱등성 보장을 위한 배치 실행 이력 테이블
CREATE TABLE IF NOT EXISTS proc_lab.bulk_discount_runs (
    batch_key        text PRIMARY KEY,
    discount_percent numeric NOT NULL,
    min_price        numeric NOT NULL,
    affected_count   integer NOT NULL DEFAULT 0,
    run_status       text NOT NULL DEFAULT 'PROCESSING',
    started_at       timestamptz NOT NULL DEFAULT clock_timestamp(),
    completed_at     timestamptz,

    CONSTRAINT ck_bulk_discount_percent
        CHECK (discount_percent > 0 AND discount_percent <= 50),

    CONSTRAINT ck_bulk_discount_min_price
        CHECK (min_price >= 0),

    CONSTRAINT ck_bulk_discount_status
        CHECK (run_status IN ('PROCESSING', 'COMPLETED'))
);

CREATE INDEX idx_orders_customer_date
    ON orders (customer_id, ordered_at DESC);

CREATE INDEX idx_orders_status
    ON orders (order_status);

CREATE INDEX idx_order_items_order
    ON order_items (order_id);


